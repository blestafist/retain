import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createThemePalettes, THEME_ROLE_NAMES } from '../src/theme/palette.ts';
import {
  DEFAULT_THEME_SETTINGS,
  THEME_CACHE_REVISION,
  THEME_CACHE_VERSION,
} from '../src/theme/settings.ts';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const generatedStylesheet = resolve(
  scriptDirectory,
  '../src/theme/generated-default.css',
);
const htmlEntrypoint = resolve(scriptDirectory, '../index.html');
const palettes = createThemePalettes(DEFAULT_THEME_SETTINGS);

function cssBlock(selector: string, mode: 'light' | 'dark'): string {
  const palette = palettes[mode];
  const declarations = THEME_ROLE_NAMES.map((role) =>
    `  --md-sys-color-${role}: ${palette[role]};`,
  );

  return `${selector} {\n  color-scheme: ${mode};\n${declarations.join('\n')}\n}`;
}

const css = [
  '/* Generated by scripts/gen-theme.ts. Do not edit by hand. */',
  cssBlock(':root', 'light'),
  cssBlock(':root[data-theme-mode="dark"]', 'dark'),
  '@media (prefers-color-scheme: dark) {',
  `  ${cssBlock(':root:not([data-theme-mode])', 'dark').replaceAll('\n', '\n  ')}`,
  '}',
  '',
].join('\n\n');

await mkdir(dirname(generatedStylesheet), { recursive: true });
let currentCss = '';
try {
  currentCss = await readFile(generatedStylesheet, 'utf8');
} catch {
  // The stylesheet is created on the first development or production build.
}

if (currentCss !== css) {
  await writeFile(generatedStylesheet, css, 'utf8');
}

const html = await readFile(htmlEntrypoint, 'utf8');
const defaultPaletteScript = /(<script id="theme-default-palette" type="application\/json">)[\s\S]*?(<\/script>)/;
if (!defaultPaletteScript.test(html)) {
  throw new Error('Default palette script placeholder was not found in index.html.');
}

const generatedHtml = html.replace(
  defaultPaletteScript,
  `$1${JSON.stringify(palettes)}$2`,
);
const rolesDeclaration = /const roles = [^\n]+;/;
if (!rolesDeclaration.test(generatedHtml)) {
  throw new Error('Theme role list declaration was not found in index.html.');
}
const generatedRolesHtml = generatedHtml.replace(
  rolesDeclaration,
  `const roles = ${JSON.stringify(THEME_ROLE_NAMES)};`,
);

function replaceCacheMeta(
  source: string,
  name: string,
  value: number,
): string {
  const meta = new RegExp(`(<meta name="${name}" content=")[^"]*(" />)`);
  if (!meta.test(source)) {
    throw new Error(`Theme cache metadata tag ${name} was not found in index.html.`);
  }

  return source.replace(meta, `$1${value}$2`);
}

const synchronizedHtml = replaceCacheMeta(
  replaceCacheMeta(
    generatedRolesHtml,
    'retain-theme-cache-version',
    THEME_CACHE_VERSION,
  ),
  'retain-theme-cache-revision',
  THEME_CACHE_REVISION,
);

if (synchronizedHtml !== html) {
  await writeFile(htmlEntrypoint, synchronizedHtml, 'utf8');
}
